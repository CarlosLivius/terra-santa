import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import sharp from 'sharp'
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--enable-webgl','--ignore-gpu-blocklist']})
try {
  for(const [name,viewport] of Object.entries({desktop:{width:1440,height:900},mobile:{width:390,height:844}})) {
    const page=await browser.newPage({viewport,reducedMotion:'reduce'})
    const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
    await page.goto('http://127.0.0.1:5173');await page.getByTestId('model-casa-1').click();await page.getByTestId('open-3d').click()
    const scene=page.getByTestId('pilot-three-scene')
    await page.waitForFunction(()=>document.querySelector('[data-testid=pilot-three-scene]')?.getAttribute('data-ready')==='true',{},{timeout:45000})
    await page.waitForFunction(()=>document.querySelector('[data-testid=pilot-build]')?.getAttribute('data-intro')==='complete',{},{timeout:10000})
    assert.equal(await scene.getAttribute('data-progress'),'100')
    assert.equal(await scene.getAttribute('data-exploring'),'true')
    const canvas=scene.locator('canvas'),canvasBox=await canvas.boundingBox(),dragAngle=await scene.getAttribute('data-azimuth')
    assert.ok(canvasBox)
    await page.mouse.move(canvasBox.x+canvasBox.width*.55,canvasBox.y+canvasBox.height*.42)
    await page.mouse.down();await page.mouse.move(canvasBox.x+canvasBox.width*.72,canvasBox.y+canvasBox.height*.42,{steps:8});await page.mouse.up();await page.waitForTimeout(350)
    assert.notEqual(await scene.getAttribute('data-azimuth'),dragAngle,'Dragging the canvas must rotate the model')
    assert.equal(await page.getByTestId('pilot-guide').count(),1)
    for(let step=0;step<3;step++)await page.getByTestId('guide-next').click()
    assert.equal(await page.getByTestId('pilot-guide').count(),0)
    const initialPixels=await sharp(await scene.locator('canvas').screenshot()).stats()
    assert.ok(initialPixels.channels[0].stdev>8,'The 3D canvas must contain rendered geometry, not a blank background')
    await page.getByTestId('construction-progress').fill('0');await page.waitForTimeout(250)
    assert.equal(await scene.getAttribute('data-furniture'),'0')
    await page.screenshot({path:`evidence/three-${name}-00.png`})
    for(const progress of [35,70,100]) {
      await page.getByTestId('construction-progress').fill(String(progress));await page.waitForTimeout(600)
      await page.screenshot({path:`evidence/three-${name}-${progress}.png`})
    }
    assert.equal(await scene.getAttribute('data-furniture'),'19')
    assert.equal(await scene.getAttribute('data-exploring'),'true')
    assert.equal(await scene.getAttribute('data-roof'),'open')
    await page.getByTestId('roof-toggle').click();await page.waitForTimeout(250)
    assert.equal(await scene.getAttribute('data-roof'),'closed')
    for(let i=0;i<8;i++)await page.getByRole('button',{name:'Aproximar',exact:true}).click()
    await page.waitForTimeout(350);assert.equal(await scene.getAttribute('data-roof'),'auto-open')
    for(let i=0;i<8;i++)await page.getByRole('button',{name:'Afastar',exact:true}).click()
    await page.waitForTimeout(350);assert.equal(await scene.getAttribute('data-roof'),'closed')
    const angle=await scene.getAttribute('data-azimuth')
    await page.getByRole('button',{name:'Girar para a direita',exact:true}).click();await page.waitForTimeout(200)
    assert.notEqual(await scene.getAttribute('data-azimuth'),angle)
    await page.getByRole('button',{name:'Sala e cozinha',exact:true}).click();await page.waitForTimeout(500)
    await page.screenshot({path:`evidence/three-${name}-living.png`})
    await page.getByRole('button',{name:'Suíte',exact:true}).click();await page.waitForTimeout(500)
    await page.screenshot({path:`evidence/three-${name}-bedroom.png`})
    await page.getByRole('button',{name:'Banheiros',exact:true}).click();await page.waitForTimeout(700)
    await page.screenshot({path:`evidence/three-${name}-bathroom.png`})
    await page.getByRole('button',{name:'Banheiro da suíte',exact:true}).click();await page.waitForTimeout(700)
    await page.screenshot({path:`evidence/three-${name}-suite-bathroom.png`})
    await page.getByRole('button',{name:'Restaurar vista',exact:true}).click();await page.waitForTimeout(300)
    await page.screenshot({path:`evidence/three-${name}-open.png`})
    await page.getByTestId('construction-progress').fill('0');await page.waitForTimeout(300)
    assert.equal(await scene.getAttribute('data-furniture'),'0')
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    assert.deepEqual(errors,[])
    console.log(`${name}: construction, furniture, camera, room views, reverse, overflow, console passed`)
    await page.close()
  }
}finally {await browser.close()}
